const validSudoku = (arr) => {
  let row = Array.from({ length: 9 }, () => new Set());
  let col = Array.from({ length: 9 }, () => new Set());
  let box = Array.from({ length: 9 }, () => new Set());

  for (let r = 0; r < 9; r++) {
    for (let c = 0; c < 9; c++) {
      if (arr[r][c] === ".") continue;

      let e = arr[r][c];
      let boxIndex = Math.max(r / 3) * 3 + Math.max(c / 3);

      if (row[r].has(e) || col[c].has(e) || box[boxIndex].has(e)) {
        return false;
      }

      row[r].push(e);
      col[c].push(e);
      box[boxIndex].push(e);
    }
  }

  return true;
};

